CREATE TABLE guess_stock_credit_facilities (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  session_id BIGINT NOT NULL,
  participant_id BIGINT NOT NULL,
  product_code VARCHAR(30) NOT NULL,
  product_name VARCHAR(40) NOT NULL,
  risk_level VARCHAR(16) NOT NULL,
  product_snapshot_json JSON NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  principal_outstanding DECIMAL(20,4) NOT NULL DEFAULT 0,
  accrued_interest DECIMAL(20,4) NOT NULL DEFAULT 0,
  last_borrow_round INT NULL,
  last_repay_round INT NULL,
  created_round INT NOT NULL,
  closed_round INT NULL,
  row_version BIGINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_guess_stock_credit_facility_participant (session_id, participant_id),
  KEY idx_guess_stock_credit_facility_status (session_id, status),
  CONSTRAINT fk_guess_stock_credit_facility_session FOREIGN KEY (session_id) REFERENCES game_sessions(id) ON DELETE CASCADE,
  CONSTRAINT fk_guess_stock_credit_facility_participant FOREIGN KEY (participant_id) REFERENCES guess_stock_participants(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE guess_stock_loan_contracts (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  facility_id BIGINT NOT NULL,
  principal_original DECIMAL(20,4) NOT NULL,
  principal_outstanding DECIMAL(20,4) NOT NULL,
  interest_rate DECIMAL(10,4) NOT NULL,
  opened_round INT NOT NULL,
  maturity_round INT NOT NULL,
  last_interest_round INT NOT NULL DEFAULT 0,
  accrued_interest DECIMAL(20,4) NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_guess_stock_loan_contract_due (facility_id, status, maturity_round),
  CONSTRAINT fk_guess_stock_loan_contract_facility FOREIGN KEY (facility_id) REFERENCES guess_stock_credit_facilities(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE guess_stock_loan_ledgers (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  session_id BIGINT NOT NULL,
  participant_id BIGINT NOT NULL,
  facility_id BIGINT NOT NULL,
  contract_id BIGINT NULL,
  round_no INT NOT NULL,
  entry_type VARCHAR(40) NOT NULL,
  principal_delta DECIMAL(20,4) NOT NULL DEFAULT 0,
  interest_delta DECIMAL(20,4) NOT NULL DEFAULT 0,
  cash_delta DECIMAL(20,4) NOT NULL DEFAULT 0,
  before_principal DECIMAL(20,4) NOT NULL,
  after_principal DECIMAL(20,4) NOT NULL,
  before_interest DECIMAL(20,4) NOT NULL,
  after_interest DECIMAL(20,4) NOT NULL,
  request_id VARCHAR(80) NULL,
  reason VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uk_guess_stock_loan_ledger_request (session_id, participant_id, request_id),
  KEY idx_guess_stock_loan_ledger_participant (session_id, participant_id, id),
  CONSTRAINT fk_guess_stock_loan_ledger_session FOREIGN KEY (session_id) REFERENCES game_sessions(id) ON DELETE CASCADE,
  CONSTRAINT fk_guess_stock_loan_ledger_participant FOREIGN KEY (participant_id) REFERENCES guess_stock_participants(id) ON DELETE CASCADE,
  CONSTRAINT fk_guess_stock_loan_ledger_facility FOREIGN KEY (facility_id) REFERENCES guess_stock_credit_facilities(id) ON DELETE CASCADE,
  CONSTRAINT fk_guess_stock_loan_ledger_contract FOREIGN KEY (contract_id) REFERENCES guess_stock_loan_contracts(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE guess_stock_credit_snapshots (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  session_id BIGINT NOT NULL,
  participant_id BIGINT NOT NULL,
  round_no INT NOT NULL,
  stage VARCHAR(20) NOT NULL,
  product_code VARCHAR(30) NULL,
  cash_value DECIMAL(20,4) NOT NULL,
  stock_value DECIMAL(20,4) NOT NULL,
  net_asset DECIMAL(20,4) NOT NULL,
  principal DECIMAL(20,4) NOT NULL,
  accrued_interest DECIMAL(20,4) NOT NULL,
  collateral_value DECIMAL(20,4) NOT NULL,
  exposure_percent DECIMAL(12,4) NOT NULL,
  ltv_percent DECIMAL(12,4) NOT NULL,
  risk_state VARCHAR(20) NOT NULL,
  forced_liquidation_shares BIGINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uk_guess_stock_credit_snapshot (session_id, participant_id, round_no, stage),
  KEY idx_guess_stock_credit_snapshot_round (session_id, round_no, stage),
  CONSTRAINT fk_guess_stock_credit_snapshot_session FOREIGN KEY (session_id) REFERENCES game_sessions(id) ON DELETE CASCADE,
  CONSTRAINT fk_guess_stock_credit_snapshot_participant FOREIGN KEY (participant_id) REFERENCES guess_stock_participants(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
