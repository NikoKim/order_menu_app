CREATE TABLE guess_stock_ai_theses (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  session_id BIGINT NOT NULL,
  participant_id BIGINT NOT NULL,
  thesis_code VARCHAR(80) NOT NULL,
  version INT NOT NULL DEFAULT 1,
  status VARCHAR(20) NOT NULL,
  created_round INT NOT NULL,
  created_phase VARCHAR(20) NOT NULL,
  created_price DECIMAL(18,4) NOT NULL,
  last_validated_round INT NOT NULL,
  market_regime VARCHAR(80) NOT NULL,
  direction VARCHAR(20) NOT NULL,
  time_horizon VARCHAR(20) NOT NULL,
  target_position_pct DECIMAL(8,4) NOT NULL,
  confidence DECIMAL(8,4) NOT NULL,
  review_after_rounds INT NOT NULL,
  expire_after_rounds INT NOT NULL,
  reason_codes_json LONGTEXT NULL,
  invalid_conditions_json LONGTEXT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uk_guess_stock_ai_thesis_code (session_id, thesis_code),
  KEY idx_guess_stock_ai_thesis_active (session_id, participant_id, status, id),
  CONSTRAINT fk_guess_stock_ai_thesis_session FOREIGN KEY (session_id) REFERENCES game_sessions(id) ON DELETE CASCADE,
  CONSTRAINT fk_guess_stock_ai_thesis_participant FOREIGN KEY (participant_id) REFERENCES guess_stock_participants(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE guess_stock_ai_decisions (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  session_id BIGINT NOT NULL,
  participant_id BIGINT NOT NULL,
  thesis_id BIGINT NULL,
  round_no INT NOT NULL,
  phase VARCHAR(20) NOT NULL,
  decision_type VARCHAR(30) NOT NULL,
  previous_target_position_pct DECIMAL(8,4) NULL,
  target_position_pct DECIMAL(8,4) NOT NULL,
  current_position_pct DECIMAL(8,4) NOT NULL,
  confidence DECIMAL(8,4) NOT NULL,
  urgency VARCHAR(20) NOT NULL,
  material_change TINYINT(1) NOT NULL DEFAULT 0,
  new_evidence_json LONGTEXT NULL,
  triggered_conditions_json LONGTEXT NULL,
  reason_codes_json LONGTEXT NULL,
  executed_direction VARCHAR(10) NOT NULL,
  executed_shares BIGINT NOT NULL DEFAULT 0,
  executed_value DECIMAL(18,4) NOT NULL DEFAULT 0,
  execution_reason VARCHAR(500) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  KEY idx_guess_stock_ai_decision_history (session_id, participant_id, round_no, id),
  KEY idx_guess_stock_ai_decision_thesis (thesis_id, id),
  CONSTRAINT fk_guess_stock_ai_decision_session FOREIGN KEY (session_id) REFERENCES game_sessions(id) ON DELETE CASCADE,
  CONSTRAINT fk_guess_stock_ai_decision_participant FOREIGN KEY (participant_id) REFERENCES guess_stock_participants(id) ON DELETE CASCADE,
  CONSTRAINT fk_guess_stock_ai_decision_thesis FOREIGN KEY (thesis_id) REFERENCES guess_stock_ai_theses(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
