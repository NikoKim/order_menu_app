            <h3>计息、期限与额度</h3>
            <p>每次放款是一笔独立贷款，玩家可以在 1 回合到该银行配置上限之间选择期限；借款当回合收盘即按未偿本金计收简单利息，不利滚利。“计息”流水显示的是新增未付利息，所以现金变化为 0 并不代表没有计算。每家银行只展示自己的合同和流水，“本行贷款”按最新创建在前、每页显示 3 份合同，并为每家银行分别记住所选页码；已结清合同会保留借款金额和已还本金，便于回看。</p>
            <p>未到期且信用状态未进入禁借或强平时，每笔贷款最多延期 2 次；每次可延期 1 回合到该银行配置的“贷款期限”上限。例如银行允许贷款 1～10 回合，则单次延期也可选择 1～10 回合。延期费为剩余本金的 0.5%，立即从未冻结现金扣除；每次延期后每回合利率增加 0.2 个百分点。贷款到期或游戏结束时先扣现金，不足再卖股；仍有债务则违约。某家银行已有债务时仍可切换到其他银行继续申请，每家银行独立维护本金、利息、期限和还款记录；为避免通过多家银行绕过风控，可用额度、股票敞口、LTV 与强平判断始终按全部银行债务合并计算。</p>
