              <div><dt>信息可信度</dt><dd>传闻、初步确认、已确认。传闻更容易被市场忽略，已确认信息更容易形成一致定价；不要为了放大行情而把所有事件设为已确认。</dd></div>
              <div><dt>意外程度</dt><dd>已有预期、一般意外、显著超预期。已有预期表示部分信息已进入当前价格；普通事件建议一般意外，真正偏离市场共识时才使用显著超预期。</dd></div>
              <div><dt>事件强度</dt><dd>弱、中、强表示事件自身的基本冲击等级，不等于最终影响层级。日常事件通常使用中，强仅用于足以改变经营预期或供需结构的事件。</dd></div>
              <div><dt>最小幅度</dt><dd>原始冲击下限，不是最终影响保底值。日常事件建议 0.5%～1.5%，重要事件建议 1.5%～3%；市场吸收后最终影响可以低于该值。</dd></div>
              <div><dt>最大幅度</dt><dd>原始冲击上限，也是事件自身的最终硬上限。日常事件建议 2%～4%，重大事件建议 4%～8%，常规玩法不建议超过 10%。</dd></div>
              <div><dt>事件链</dt><dd>相同 chainKey 表示同一故事，chainStep 表示阶段；前置/后续标签和概率加成提高合理后续事件的候选机会，最大深度限制故事长度。标准建议 2～4 步，加成 10%～30%。</dd></div>
              <div><dt>事件链标识</dt><dd>把属于同一叙事的事件归组，例如 DEMAND_SLOWDOWN。留空表示独立事件；建议使用稳定的大写英文标识，同一链内保持完全一致。</dd></div>
              <div><dt>事件链步骤</dt><dd>0～20 的顺序编号，较小步骤先作为故事起点。建议从 0 或 1 连续编号，不要重复使用同一步骤表达互斥结局，互斥情节应拆分标签。</dd></div>
              <div><dt>前置标签</dt><dd>只有历史上已释放相应后续标签时，事件才得到链路匹配机会。多个标签用逗号分隔；建议只填真正必要的因果条件，避免链条永远无法触发。</dd></div>
              <div><dt>后续标签</dt><dd>事件出现后写入的故事线索，供之后事件的前置标签匹配。使用简短稳定的业务词，例如 ORDERS、INVENTORY；大小写和拼写应统一。</dd></div>
              <div><dt>后续概率加成</dt><dd>前置标签匹配时增加候选机会，范围 0%～100%。标准建议 10%～30%，强因果关系可用 30%～60%；100% 仍不代表必然发生。</dd></div>
              <div><dt>最大链深度</dt><dd>限制同一故事在一局内可推进的层数，防止单一叙事长期占据事件池。短局建议 2～3，标准局 3～5，长局不建议超过 8。</dd></div>
              <div><dt>启用事件</dt><dd>关闭后保留配置但不会进入候选池。发布前建议至少准备 8～15 条启用事件，并检查正负方向、日常与重大事件是否大致平衡。</dd></div>
