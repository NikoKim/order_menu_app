              <div><dt>强平 LTV</dt><dd>达到后系统卖出恢复风险所需的最少股数。建议比禁借线高 3～8 个百分点；间距过小会频繁强平，间距过大则可能在剧烈下跌时直接违约。</dd></div>
              <div><dt>恢复 LTV</dt><dd>强平希望回到的目标 LTV，越低代表卖出的股票越多。建议比警戒线低 4～10 个百分点，让强平后保留可见安全垫。</dd></div>
            </dl>
            <div class="formula"><strong>必须满足</strong><code>放款 LTV &lt; 警戒 LTV &lt; 禁借 LTV &lt; 强平 LTV；恢复 LTV &lt; 警戒 LTV。最大敞口通常不应明显高于 100% + 债务/净资产上限。</code></div>
            <h3>推荐配置</h3>
            <dl>
              <div><dt>新手体验</dt><dd>开启稳健和进取银行；最大敞口 150%/180%，每回合利率 0.3%～0.6%，期限 4 回合，并为各条 LTV 线保留较宽间隔。</dd></div>
              <div><dt>标准竞技</dt><dd>直接使用默认三档银行：150%/200%/250% 敞口、0.4%/0.8%/1.2% 利率、3/3/2 回合期限，极端银行保持关闭。</dd></div>
              <div><dt>高风险竞赛</dt><dd>开启稳健、进取和高风险；高风险敞口建议 220%～250%，利率 1.0%～1.4%，期限 2～3 回合。不要同时提供低利率、长期限和宽松 LTV。</dd></div>
              <div><dt>极端沙盒</dt><dd>可开启 280%～300% 敞口，但建议缩短总回合、保留至少 1.5% 利率并明确提示强平风险。它适合测试市场连锁卖压，不适合作为默认规则。</dd></div>
            </dl>
            <p>推荐设置顺序是：先决定希望玩家最高持有多少股票敞口，再设置两项贷款额度，随后从放款到强平依次排好 LTV 阶梯，最后用利率、期限、最低借款和冷却控制使用成本与频率。单家银行的实际可借额度取多项限制中的最小值，并扣除玩家在其他银行已经占用的全局风险空间，因此单独提高某一项不一定会增加额度。</p>
            <h3>AI 如何使用</h3>
            <p>AI 模型只输出 0%～300% 的目标股票敞口，不决定借款金额。后端先执行敞口步长和 AI 风险上限，再从能满足目标的银行中选择利率最低者，计算可借额度、预计 LTV 和买入数量。已有债务时不会自动换行；目标降至 100% 以下后，卖出所得会优先自动还债。普通加杠杆最多前进 15 个百分点，强信号最多 30 个百分点；主动去杠杆速度可加倍，强平不受此步长限制。</p>
