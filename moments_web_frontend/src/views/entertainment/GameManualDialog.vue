            <h3>决策过程</h3>
            <p>AI 同一时间维护一个活动投资观点，包含观点编号和版本、方向、市场判断、建立价格、目标敞口、置信度、复核周期、有效期及结构化失效条件。模型只输出 CREATE、KEEP、ADJUST、REPLACE 或 CLOSE 和目标股票敞口，不再输出 BUY/SELL、具体股数或贷款金额；后端比较当前敞口与目标后自动推导授信和订单。</p>
            <p>AI 对手数量不设固定上限，但数量越多，模型调用费用、阶段等待时间和市场订单冲击都会增加。所有 AI 在同一阶段读取同一份冻结市场快照。紧凑决策包包含最近价格、3/8/20 回合收益与斜率、短长波动、回撤、趋势/波动双维状态、状态年龄、公开事件、尚未消化的事件冲击和不含其他 AI 待成交意图的订单流。没有重要新证据、复核到期或风险触发时直接 KEEP；同一回撤区间和残余事件不会反复强制调用模型。</p>
            <p>目标差低于风格缓冲区时不交易；计划金额过小、持有期不足、换手额度耗尽或价格冲击过大时也不会下单。普通信号单次最多移动 15 个仓位百分点，强信号最多 30 个百分点；观点失效或极端风险才可越过步长。跨回合反向交易默认冷却 2 回合，确认的状态反转、观点失效或极端风险可以越过冷却，但仍不能绕过资金与风控。</p>
