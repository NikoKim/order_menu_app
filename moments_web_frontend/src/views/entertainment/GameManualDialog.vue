            <h2>银行融资与杠杆</h2>
            <p>创建者开启银行融资后，可以选择“开盘内融资”或“独立银行阶段”。开盘内融资不增加单独的贷款阶段，玩家在开盘交易阶段内同时借款和下单，两者共用交易倒计时；独立银行阶段会在开盘前增加贷款期，由全员确认或贷款倒计时推进。两种模式都保留收盘后的还贷能力，银行页顶部通过银行名称切换产品，玩家可以同时向多家银行借款，也可以分别查看和归还债务。借款不是额外收益：实时资产、收益率排名和最终结算都会扣除全部银行的本金与未付利息。</p>
            <div class="formula"><strong>核心口径</strong><code>净资产 = 现金 + 股票市值 - 本金 - 利息；股票敞口 = 股票市值 / 净资产；LTV = 有效债务 /（现金 + 股票市值 × (1 - 抵押折扣)）</code></div>
