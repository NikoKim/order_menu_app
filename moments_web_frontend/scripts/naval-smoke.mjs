async function checkLayout(page, name) {
  await page.waitForFunction(() => [...document.querySelectorAll('.naval-board')].every(element => element.querySelector('canvas')?.dataset.renderer === 'phaser-3.90' && !element.classList.contains('is-loading')))
  await page.waitForTimeout(450)
  const layout = await page.evaluate(() => ({ width: innerWidth, overflow: document.documentElement.scrollWidth > innerWidth, boards: [...document.querySelectorAll('.naval-board')].map(el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, right: r.right, bottom: r.bottom, width: r.width, height: r.height } }), sidebar: document.querySelector('.mobile-game') ? null : document.querySelector('.battle-sidebar')?.getBoundingClientRect().toJSON(), pixels: [...document.querySelectorAll('.naval-board canvas')].map(c => { const values = c.getContext('2d').getImageData(0, 0, c.width, c.height).data; const unique = new Set(); for (let i = 0; i < values.length; i += 64) unique.add(`${values[i]},${values[i + 1]},${values[i + 2]}`); return unique.size }) }))
  assert(!layout.overflow, `${name}: horizontal overflow`)
  if (layout.boards.length) {
    if (layout.boards.length === 2) assert(layout.boards[0].right <= layout.boards[1].x, `${name}: boards overlap`)
    if (layout.sidebar) assert(layout.boards.at(-1).right <= layout.sidebar.x, `${name}: sidebar overlap`)
    assert(layout.pixels.every(n => n > 6), `${name}: blank canvas`)
  }
  await page.screenshot({ path: path.join(output, `${name}.png`), fullPage: true })
  return layout
}
